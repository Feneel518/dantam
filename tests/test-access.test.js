import {test,after} from 'node:test';
import assert from 'node:assert/strict';
import request from 'supertest';
process.env.SQLITE_PATH=':memory:';process.env.ENCRYPTION_KEY='f'.repeat(64);process.env.NODE_ENV='test';process.env.APP_URL='http://localhost:3000';
const {app,errorHandler}=await import('../server/app.js');app.use(errorHandler);
const {one,run,closeDb}=await import('../server/db.js');
const {paid}=await import('../server/workflows.js');
after(closeDb);
test('private complimentary Growth access is bounded and never opens Pro or checkout',async()=>{
 const a=request.agent(app),post=(path,body)=>a.post(path).set('Origin',process.env.APP_URL).send(body);
 assert.equal((await post('/api/auth/register',{email:'testgrowth@example.in',password:'Private test password 2026!',name:'Growth Test Clinic',phone:'9999000777',city:'Surat'})).status,201);
 let clinic=await one('SELECT * FROM clinics');
 const data={...JSON.parse(clinic.data),demo:true,testAccess:true};
 await run('UPDATE clinics SET data=?,plan=?,billing_status=?,paid_until=? WHERE id=?',[JSON.stringify(data),'growth','testing',new Date(Date.now()+86400000).toISOString(),clinic.id]);
 const w=(await a.get('/api/workspace')).body;
 assert.equal(w.clinic.paid,true);assert.equal(w.clinic.plan,'growth');assert.equal(w.clinic.subscriptionId,null);assert.equal(w.clinic.testAccess,true);assert.equal(w.patients.length,0);
 assert.equal((await post('/api/care/task',{title:'Check follow-up',status:'pending',dueDate:'2026-10-03'})).status,201);
 const patient=await post('/api/patients',{name:'Test Patient',phone:'9999000778',consent:false,recallDate:''});
 assert.equal((await post('/api/care/recall',{patientId:patient.body.id,title:'Routine recall',status:'upcoming',dueDate:'2026-10-03'})).status,201);
 assert.equal((await post('/api/care/treatment',{patientId:patient.body.id,title:'Pro treatment',status:'proposed'})).status,402);
 assert.equal((await post('/api/care/campaign',{title:'Pro reactivation',status:'draft'})).status,402);
 assert.equal((await post('/api/team/invite',{email:'staff@example.in',role:'doctor'})).status,402);
 const billing=await post('/api/billing/subscribe',{plan:'growth'});assert.equal(billing.status,400);assert.match(billing.body.error,/complimentary/);
 const whatsapp=await post('/api/whatsapp',{});assert.equal(whatsapp.status,400);assert.match(whatsapp.body.error,/private test clinic/);
 clinic=await one('SELECT * FROM clinics');
 assert.ok(!paid({...clinic,paid_until:'2000-01-01T00:00:00.000Z'}));
 assert.ok(!paid({...clinic,data:JSON.stringify({...data,testAccess:false})}));
 assert.ok(!paid({...clinic,data:JSON.stringify({...data,demo:false})}));
 assert.ok(!paid({...clinic,plan:'free'}));
 const patch=await a.patch('/api/clinic').set('Origin',process.env.APP_URL).send({...data,name:clinic.name,testAccess:false,demo:false});
 assert.equal(patch.status,200);const saved=JSON.parse((await one('SELECT data FROM clinics')).data);assert.equal(saved.testAccess,true);assert.equal(saved.demo,true);
 assert.equal((await post('/api/care/treatment',{patientId:patient.body.id,title:'Still restricted',status:'proposed'})).status,402);
});
